/**
 * CodeSense AI — PR Review page (CodeRabbit-style).
 * by Nitish Singh
 *
 * Paste a unified diff (`git diff main...feature`) → get a walkthrough, risk
 * level, per-file summary, suggested review order and line-anchored comments
 * with committable suggestions. Comments are validated server-side against the
 * lines the PR actually changed (hallucination guard).
 */
import { useEffect, useMemo, useRef, useState } from "react";
import { useSearchParams } from "react-router-dom";
import { reviewDiff, fetchGithubPR } from "../api";
import { friendlyError } from "../lib/errors";
import { getSettings } from "../lib/theme";
import { downloadTextFile } from "../lib/report";
import { SAMPLE_PR_DIFF, SAMPLE_PR_TITLE } from "../lib/sampleDiff";

const STEPS = ["Parsing diff", "Reviewing with Gemini", "Verifying against changed lines", "Scoring"];
const SEV_ORDER = { high: 0, medium: 1, low: 2 };

function CopyButton({ text, label = "copy", className = "copy-btn" }) {
  const [done, setDone] = useState(false);
  return (
    <button
      type="button"
      className={className}
      onClick={async () => {
        try {
          await navigator.clipboard.writeText(text);
          setDone(true);
          setTimeout(() => setDone(false), 1500);
        } catch {
          /* clipboard unavailable */
        }
      }}
    >
      {done ? "✓ copied" : label}
    </button>
  );
}

function SteppedLoader() {
  const [active, setActive] = useState(0);
  useEffect(() => {
    const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
    if (reduced) {
      setActive(STEPS.length - 1);
      return undefined;
    }
    const id = window.setInterval(() => setActive((i) => Math.min(i + 1, STEPS.length - 1)), 1600);
    return () => window.clearInterval(id);
  }, []);
  return (
    <div className="pr-card pr-loader" role="status" aria-live="polite">
      <h2>Reviewing pull request</h2>
      <ol className="pr-steps">
        {STEPS.map((s, i) => (
          <li key={s} className={i < active ? "done" : i === active ? "active" : ""}>
            <span className="pr-step-dot" aria-hidden="true">{i < active ? "✓" : ""}</span>
            {s}
          </li>
        ))}
      </ol>
      <div className="skeleton-list" aria-hidden="true">
        {[0, 1, 2].map((i) => <div key={i} className="skeleton-row" style={{ animationDelay: `${i * 120}ms` }} />)}
      </div>
    </div>
  );
}

function splitTag(text = "") {
  const m = text.match(/^\s*\[([^\]]*CWE-\d+[^\]]*)\]\s*/i);
  return m ? { tag: m[1].trim(), rest: text.slice(m[0].length) } : { tag: null, rest: text };
}

function buildReport(result, title) {
  const L = [];
  L.push(`# PR Review${title ? `: ${title}` : ""}`);
  L.push("");
  L.push(`**Risk:** ${result.risk} · **Quality:** ${result.grade} (${result.quality_score}/10) · ` +
    `${result.issue_count.high} high / ${result.issue_count.medium} medium / ${result.issue_count.low} low`);
  L.push("");
  L.push("## Summary", "", result.summary, "");
  if (result.walkthrough) L.push("## Walkthrough", "", result.walkthrough, "");
  L.push("## Files", "");
  result.files.forEach((f) => L.push(`- \`${f.path}\` (${f.status}, +${f.additions}/-${f.deletions}): ${f.change}`));
  L.push("", `## Review comments (${result.comments.length})`, "");
  result.comments.forEach((c) => {
    L.push(`### [${c.severity.toUpperCase()}] ${c.title}`);
    L.push(`\`${c.path}:${c.line}\` · ${c.type}`, "", c.explanation, "");
    if (c.suggestion) L.push("Suggested change:", "", "```", c.suggestion, "```", "");
  });
  L.push("---", "_Generated by CodeSense AI · by Nitish Singh. Comments verified against changed lines._");
  return L.join("\n");
}

export default function PRReview() {
  const [params] = useSearchParams();
  const [diff, setDiff] = useState("");
  const [title, setTitle] = useState("");
  const [profile, setProfile] = useState(() => getSettings().strictness);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [result, setResult] = useState(null);
  const [sev, setSev] = useState("all");
  const [collapsed, setCollapsed] = useState(() => new Set());
  const resultRef = useRef(null);

  const [prUrl, setPrUrl] = useState("");
  const [fetching, setFetching] = useState(false);
  async function loadFromGithub(e) {
    e?.preventDefault();
    if (!prUrl.trim() || fetching) return;
    setFetching(true); setError(""); setResult(null);
    try {
      const pr = await fetchGithubPR(prUrl.trim());
      setDiff(pr.diff); setTitle(pr.title);
    } catch (err) {
      setError(err.message || "Could not load that PR.");
    } finally { setFetching(false); }
  }

  function loadSample() {
    setDiff(SAMPLE_PR_DIFF);
    setTitle(SAMPLE_PR_TITLE);
    setResult(null);
    setError("");
  }

  useEffect(() => {
    if (params.get("demo")) loadSample();
  }, [params]);

  async function run(e) {
    e?.preventDefault();
    if (busy || !diff.trim()) return;
    setBusy(true);
    setError("");
    setResult(null);
    setSev("all");
    setCollapsed(new Set());
    try {
      setResult(await reviewDiff({ diff, title, profile }));
    } catch (err) {
      setError(err.message || "Review failed.");
    } finally {
      setBusy(false);
    }
  }

  useEffect(() => {
    if (result) resultRef.current?.scrollIntoView({ behavior: "smooth", block: "start" });
  }, [result]);

  const groups = useMemo(() => {
    if (!result) return [];
    const order = result.sequence?.length ? result.sequence : result.files.map((f) => f.path);
    const files = [...result.files].sort((a, b) => order.indexOf(a.path) - order.indexOf(b.path));
    return files.map((f) => ({
      file: f,
      all: result.comments.filter((c) => c.path === f.path),
      comments: result.comments
        .filter((c) => c.path === f.path && (sev === "all" || c.severity === sev))
        .sort((a, b) => SEV_ORDER[a.severity] - SEV_ORDER[b.severity] || a.line - b.line),
    }));
  }, [result, sev]);

  function toggle(path) {
    setCollapsed((prev) => {
      const next = new Set(prev);
      next.has(path) ? next.delete(path) : next.add(path);
      return next;
    });
  }

  const fe = error ? friendlyError(error) : null;
  const total = result?.comments.length ?? 0;
  const shown = groups.reduce((n, g) => n + g.comments.length, 0);

  return (
    <main className="pr-page">
      <header className="pr-hero">
        <span className="landing-eyebrow">Pull request review</span>
        <h1>Review a PR like a senior engineer would.</h1>
        <p>
          Paste a <code>git diff</code>. The AI comments, then CodeSense verifies each one
          against the lines that really changed, so invented files and lines never reach you.
        </p>
      </header>

      <form className="pr-card pr-form" onSubmit={run}>
        <div className="pr-row">
          <label className="pr-field grow">
            <span>PR title</span>
            <input
              placeholder="e.g. Add payment webhook (optional)"
              value={title}
              maxLength={200}
              onChange={(e) => setTitle(e.target.value)}
            />
          </label>
          <label className="pr-field">
            <span>Profile</span>
            <select value={profile} onChange={(e) => setProfile(e.target.value)}>
              <option value="chill">Chill: only real problems</option>
              <option value="assertive">Assertive: strict, incl. style</option>
            </select>
          </label>
        </div>
        <div className="pr-field gh-fetch">
          <span>GitHub PR link (public repos)</span>
          <div className="pr-row">
            <input
              type="url" value={prUrl} onChange={(e) => setPrUrl(e.target.value)}
              placeholder="https://github.com/owner/repo/pull/123"
              onKeyDown={(e) => e.key === "Enter" && loadFromGithub(e)}
              aria-label="GitHub pull request link"
            />
            <button type="button" className="btn btn-ghost" onClick={loadFromGithub} disabled={fetching || !prUrl.trim()}>
              {fetching ? "Loading…" : "Load PR"}
            </button>
          </div>
        </div>
        <label className="pr-field">
          <span>Or paste a unified diff</span>
          <textarea
            placeholder={"Paste a unified diff, e.g. the output of:\ngit diff main...my-branch"}
            value={diff}
            onChange={(e) => setDiff(e.target.value)}
            spellCheck={false}
          />
        </label>
        <div className="pr-row">
          <button type="button" className="btn btn-ghost btn-lg" onClick={loadSample} disabled={busy}>
            ⊞ Load sample PR
          </button>
          <button type="submit" className="btn btn-primary btn-lg" disabled={busy || !diff.trim()}>
            {busy ? "Reviewing…" : "▶ Review PR"}
          </button>
          <span className="pr-muted pr-count">{diff ? `${diff.length.toLocaleString()} chars` : "no diff yet"}</span>
        </div>
      </form>

      {busy && <SteppedLoader />}

      {fe && !busy && (
        <div className="pr-card pr-errorcard" role="alert">
          <span className="error-symbol">[!] {fe.kind}</span>
          <p className="error-title">{fe.title}</p>
          <p className="error-detail">{fe.hint}</p>
          <button type="button" className="btn btn-primary" onClick={run}>↺ Retry</button>
          <details className="error-tech"><summary>technical details</summary><code>{error}</code></details>
        </div>
      )}

      {!busy && !result && !fe && (
        <div className="pr-card pr-empty">
          <p className="empty-title">No review yet</p>
          <p className="empty-sub">
            Click <strong>Load sample PR</strong> for a ready-made diff containing a SQL injection,
            a hardcoded secret and a missing null check, then hit <strong>Review PR</strong>.
          </p>
        </div>
      )}

      {result && !busy && (
        <div ref={resultRef} className="pr-results">
          <section className="pr-card pr-summary">
            <div className="pr-head">
              <h2>Walkthrough</h2>
              <span className={`pr-pill ${result.risk}`}>risk: {result.risk}</span>
              <span className="pr-pill grade">{result.grade} · {result.quality_score}/10</span>
              <span className="pr-muted">
                {result.issue_count.high} high · {result.issue_count.medium} medium · {result.issue_count.low} low
              </span>
              <span className="pr-spacer" />
              <CopyButton text={buildReport(result, title)} label="copy report (.md)" className="btn btn-ghost btn-xs" />
              <button
                type="button"
                className="btn btn-ghost btn-xs"
                onClick={() => downloadTextFile("codesense-pr-review.md", buildReport(result, title))}
              >
                ⬇ export .md
              </button>
            </div>
            <p>{result.summary}</p>
            {result.walkthrough && <p className="pr-muted">{result.walkthrough}</p>}
            <p className="pr-verified">✓ {total} comment{total !== 1 ? "s" : ""} verified against the lines this PR changed</p>
          </section>

          <section className="pr-card">
            <div className="pr-head">
              <h2>Review comments ({shown}{shown !== total ? ` of ${total}` : ""})</h2>
              <span className="pr-spacer" />
              <div className="filter-bar nopad" role="group" aria-label="Filter by severity">
                {["all", "high", "medium", "low"].map((k) => (
                  <button key={k} type="button" aria-pressed={sev === k}
                    className={`fchip sev-${k} ${sev === k ? "on" : ""}`} onClick={() => setSev(k)}>
                    {k}
                  </button>
                ))}
              </div>
            </div>

            {total === 0 && <p className="pr-muted">No issues found. Nice PR.</p>}

            {groups.map(({ file, all, comments }) => {
              const open = !collapsed.has(file.path);
              if (sev !== "all" && comments.length === 0) return null;
              return (
                <div className="pr-group" key={file.path}>
                  <button
                    type="button"
                    className="pr-group-h"
                    aria-expanded={open}
                    onClick={() => toggle(file.path)}
                  >
                    <span className="pr-caret" aria-hidden="true">{open ? "▾" : "▸"}</span>
                    <code>{file.path}</code>
                    <span className="pr-pill">{file.status}</span>
                    <span className="pr-add">+{file.additions}</span>
                    <span className="pr-del">−{file.deletions}</span>
                    <span className="pr-spacer" />
                    <span className="pr-muted">{all.length} comment{all.length !== 1 ? "s" : ""}</span>
                  </button>
                  {open && (
                    <div className="pr-group-b">
                      {file.change && <p className="pr-muted pr-change">{file.change}</p>}
                      {comments.length === 0 && <p className="pr-muted">No comments for this file.</p>}
                      {comments.map((c) => (
                        <article className={`pr-comment sev-${c.severity}`} key={`${c.path}:${c.line}:${c.title}`}>
                          <div className="pr-comment-h">
                            <span className={`pr-pill ${c.severity}`}>{c.severity}</span>
                            <span className="pr-pill">{c.type}</span>
                            <code>L{c.line}</code>
                            <strong>{c.title}</strong>
                            {splitTag(c.explanation).tag && <span className="cwe-chip">{splitTag(c.explanation).tag}</span>}
                          </div>
                          <div className="pr-comment-b">
                            <p>{splitTag(c.explanation).rest}</p>
                            {c.suggestion && (
                              <div className="pr-sugg-wrap">
                                <pre className="pr-sugg"><code>{c.suggestion}</code></pre>
                                <CopyButton text={c.suggestion} />
                              </div>
                            )}
                          </div>
                        </article>
                      ))}
                    </div>
                  )}
                </div>
              );
            })}
          </section>
        </div>
      )}
    </main>
  );
}
