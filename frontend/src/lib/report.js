import { computeScore } from "./score";

const SEVERITY_RANK = { high: 0, medium: 1, low: 2 };
const TYPE_LABEL = {
  bug: "Bug",
  security: "Security",
  performance: "Performance",
  style: "Style",
};

function pad2(n) {
  return String(n).padStart(2, "0");
}

function stamp(date = new Date()) {
  return (
    `${date.getFullYear()}-${pad2(date.getMonth() + 1)}-${pad2(date.getDate())} ` +
    `${pad2(date.getHours())}:${pad2(date.getMinutes())}`
  );
}

function fence(code, lang = "") {
  const safe = String(code ?? "").replace(/```/g, "``​`");
  return "```" + lang + "\n" + safe.replace(/\s+$/, "") + "\n```";
}

/**
 * Compile a full Markdown review report.
 * @returns {{ filename: string, markdown: string }}
 */
export function buildMarkdownReport({ code, language, results }) {
  const summary = results?.summary ?? "";
  const issues = Array.isArray(results?.issues) ? results.issues : [];
  const counts = results?.issue_count ?? { high: 0, medium: 0, low: 0 };
  const model = results?.model ?? "gemini";
  const { display, grade, label } = computeScore(counts);
  const lang = language && language !== "auto" ? language : "";

  const ordered = [...issues].sort(
    (a, b) =>
      (SEVERITY_RANK[a.severity] ?? 9) - (SEVERITY_RANK[b.severity] ?? 9) ||
      (a.line ?? 1e9) - (b.line ?? 1e9)
  );

  const lines = [];
  lines.push("# CodeSense AI — Code Review Report");
  lines.push("");
  lines.push("**CodeSense AI · by Nitish Singh**");
  lines.push("");
  lines.push(`- **Generated:** ${stamp()}`);
  lines.push(`- **Language:** ${language || "auto"}`);
  lines.push(`- **Model:** ${model}`);
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("## Quality Score");
  lines.push("");
  lines.push(`### ${display} / 10 — Grade ${grade} (${label})`);
  lines.push("");
  lines.push("| Severity | Count |");
  lines.push("| -------- | ----: |");
  lines.push(`| High | ${counts.high ?? 0} |`);
  lines.push(`| Medium | ${counts.medium ?? 0} |`);
  lines.push(`| Low | ${counts.low ?? 0} |`);
  lines.push(
    `| **Total** | **${(counts.high ?? 0) + (counts.medium ?? 0) + (counts.low ?? 0)}** |`
  );
  lines.push("");
  lines.push("## Summary");
  lines.push("");
  lines.push(summary.trim() || "_No summary provided._");
  lines.push("");
  lines.push(`## Issues (${ordered.length})`);
  lines.push("");

  if (ordered.length === 0) {
    lines.push("_No issues found — the code looks clean._");
    lines.push("");
  } else {
    ordered.forEach((issue, idx) => {
      const where = issue.line != null ? ` — line ${issue.line}` : "";
      const typeLabel = TYPE_LABEL[issue.type] ?? issue.type;
      lines.push(
        `### ${idx + 1}. [${String(issue.severity).toUpperCase()} · ${typeLabel}] ${issue.title}${where}`
      );
      lines.push("");
      lines.push(issue.explanation?.trim() || "_No explanation provided._");
      lines.push("");
      lines.push("**Suggested fix:**");
      lines.push("");
      lines.push(fence(issue.suggested_fix, lang));
      lines.push("");
    });
  }

  lines.push("---");
  lines.push("");
  lines.push("## Reviewed Source");
  lines.push("");
  lines.push(fence(code, lang));
  lines.push("");
  lines.push("---");
  lines.push("");
  lines.push("_Report generated by CodeSense AI · by Nitish Singh_");
  lines.push("");

  const dateStr = stamp().replace(/[: ]/g, "-");
  return {
    filename: `codesense-review_${lang || "code"}_${dateStr}.md`,
    markdown: lines.join("\n"),
  };
}

/** Trigger a browser download of a text file. */
export function downloadTextFile(filename, text, mime = "text/markdown;charset=utf-8") {
  const blob = new Blob([text], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}
